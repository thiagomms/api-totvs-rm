SELECT
	PFUNC.CHAPA,
	PFUNC.NOME,
	PANOTAC.DTANOTACAO,
	PANOTAC.DTRESOLUCAO,
	PANOTAC.TEXTO,
	PFUNC.CODSECAO,
	PSECAO.DESCRICAO,
	PFCOMPL.TURNO,
	PFCOMPL.TURMA
 
FROM PFUNC (NOLOCK)
 
	INNER JOIN PPESSOA (NOLOCK)
	ON PPESSOA.CODIGO = PFUNC.CODPESSOA
 
	INNER JOIN PANOTAC (NOLOCK)
	ON PANOTAC.CODPESSOA = PPESSOA.CODIGO
	INNER JOIN PFCOMPL (NOLOCK)
	ON PFCOMPL.CODCOLIGADA = PFUNC.CODCOLIGADA 
	AND PFCOMPL.CHAPA = PFUNC.CHAPA
	INNER JOIN PSECAO (NOLOCK)
	ON PSECAO.CODCOLIGADA = PFUNC.CODCOLIGADA 
	AND PSECAO.CODIGO = PFUNC.CODSECAO
 
WHERE
 
	PFUNC.CODCOLIGADA = 1
	AND PFUNC.CODSITUACAO <> 'D'
	AND PANOTAC.TIPO = '33'
	AND TEXTO LIKE 'Troca de plantão realizada via Vivi Bot%'
	AND PANOTAC.DTRESOLUCAO >= '2026-09-18'
	AND PANOTAC.DTRESOLUCAO <= '2026-10-18'